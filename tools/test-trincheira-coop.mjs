// Co-op da Trincheira pelo servidor real: dois jogadores, mensagens novas e snapshot com o bloco tr. Uso: node tools/test-trincheira-coop.mjs  (sobe o servidor sozinho)
import { spawn } from 'node:child_process';
import WebSocket from 'ws';
const PORT = 3911;
const srv = spawn('npx', ['tsx', 'src/server/main.ts'], { env: { ...process.env, PORT: String(PORT) }, stdio: ['ignore', 'pipe', 'pipe'] });
let ok = 0, bad = 0;
const check = (n, c, d = '') => { c ? ok++ : bad++; console.log(`${c ? 'ok  ' : 'FALHOU'} ${n}${d ? ` (${d})` : ''}`); };
await new Promise((r) => { srv.stdout.on('data', (b) => String(b).includes('3911') || String(b).toLowerCase().includes('rodando') || String(b).includes('ouvindo') ? r() : null); setTimeout(r, 6000); });
const mkc = () => new Promise((res) => { const ws = new WebSocket(`ws://127.0.0.1:${PORT}`); const c = { ws, snaps: [], evs: [], id: '', msgs: [] }; ws.on('message', (d) => { const m = JSON.parse(String(d)); c.msgs.push(m); if (m.t === 'welcome') c.id = m.id; if (m.t === 'snap') c.snaps.push(m.s); if (m.t === 'ev') c.evs.push(...m.list); if (m.t === 'started') c.you = m.you; }); ws.on('open', () => res(c)); });
const send = (c, m) => c.ws.send(JSON.stringify(m));
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const a = await mkc(), b = await mkc();
await wait(300);
send(a, { t: 'create', name: 'Ana', level: 1, startRound: 1, mapId: 'trincheira' });
await wait(400);
const lobby = a.msgs.find((m) => m.t === 'lobby');
send(b, { t: 'join', code: lobby.code, name: 'Beto', level: 1 });
await wait(400);
send(a, { t: 'start' });
await wait(1500);
check('partida começa no mapa Trincheira', a.msgs.some((m) => m.t === 'started' && m.mapId === 'trincheira'));
const last = () => a.snaps[a.snaps.length - 1];
check('snapshot do co-op traz o bloco tr', !!last()?.tr && last().tr.gens.length === 6);
const bytes = JSON.stringify(last()).length;
check('snapshot pequeno o bastante', bytes < 20000, `${bytes} bytes`);
// a pá, o hold e o artillery não derrubam a sala
const { tsImport } = await import('tsx/esm/api');
const { getMap } = await tsImport('../src/shared/map/index.ts', import.meta.url);
const pa = getMap('trincheira').interactables.find((i) => i.id === 'pa-0').use;
send(a, { t: 'state', x: pa[0] - 1, y: 0, z: pa[1], yaw: 0, pitch: 0, crouch: false, speed: 0 });
send(a, { t: 'interact', id: 'pa-0', weapon: 'pistol' });
send(a, { t: 'hold', id: 'monte-0' });
send(a, { t: 'hold', id: null });
send(a, { t: 'artillery', x: 90, y: 1.6, z: 54, vx: 0, vy: 2, vz: -10 });
send(b, { t: 'launch', weapon: 'cajado-fogo', x: 99, y: 1.5, z: 50, dx: 0, dy: 0, dz: -1 });
send(b, { t: 'shoot', weapon: 'pistol', hits: [], ray: [99, 1.5, 50, 0, 0, -1] });
await wait(1200);
const n0 = a.snaps.length;
await wait(1000);
check('servidor segue enviando snapshots', a.snaps.length > n0 + 10, `${a.snaps.length - n0} em 1 s`);
const me = last().players.find((p) => p.id === a.id);
check('a pá foi entregue ao jogador certo no co-op', me?.shovel === true && last().players.find((p) => p.id === b.id)?.shovel === false);
check('segundo jogador também recebe os snapshots', b.snaps.length > 20);
srv.kill();
console.log(`\n${ok} ok, ${bad} falharam`);
process.exit(bad ? 1 : 0);
