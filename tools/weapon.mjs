// Captura a arma em vários estados: parada, mirando, recarregando, faca, correndo.
import { chromium } from 'playwright-core';
const out = process.argv[2] ?? '.';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--ignore-gpu-blocklist', '--use-angle=d3d11'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
await page.goto('http://localhost:5173/?autoplay');
await page.click('#btn-solo');
await page.waitForFunction(() => window.__game, null, { timeout: 60000 });
await page.evaluate(() => window.__game.debugView(0, 20, 0, 0));
await page.waitForTimeout(1200);
await page.screenshot({ path: `${out}/w0-parado.png` });
await page.mouse.move(640, 360);
await page.mouse.down({ button: 'right' });
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/w1-mira.png` });
await page.mouse.up({ button: 'right' });
await page.mouse.down({ button: 'left' });
await page.mouse.up({ button: 'left' });
await page.waitForTimeout(25);
await page.screenshot({ path: `${out}/w2-disparo.png` });
await page.waitForTimeout(400);
await page.keyboard.down('KeyR');
await page.keyboard.up('KeyR');
await page.waitForTimeout(350);
await page.screenshot({ path: `${out}/w3-recarga-a.png` });
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/w4-recarga-b.png` });
await page.waitForTimeout(1200);
await page.keyboard.down('KeyV');
await page.keyboard.up('KeyV');
await page.waitForTimeout(150);
await page.screenshot({ path: `${out}/w5-faca.png` });
await page.waitForTimeout(800);
await page.keyboard.down('KeyW');
await page.keyboard.down('ShiftLeft');
await page.waitForTimeout(700);
await page.screenshot({ path: `${out}/w6-correndo.png` });
await page.keyboard.up('ShiftLeft');
await page.keyboard.up('KeyW');
const ammo = await page.evaluate(() => [window.__game.weapon.ammo, window.__game.weapon.reserve]);
console.log('munição', ammo);
await browser.close();
